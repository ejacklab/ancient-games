# --- reading a report -------------------------------------------------------------------------------------------

STATES = ("needs a reviewer", "not applicable", "could not run", "pass", "fail")

_PREFIXED = re.compile(r"(?P<prefix>SoT|CACHES):(?P<id>[A-Za-z]+[0-9][0-9A-Za-z.]*)")
_OWN = re.compile(r"(?<![\w:])(?P<id>F[123])(?![\w.])")
_DECORATION = re.compile(r"^[\s>*|#\-0-9.`_]*$")
_RESULT = re.compile(
    r"^[^A-Za-z(]*(?:\((?P<l1>[^)]*)\)|(?P<l2>MUST|SHOULD|guidance)\b)?[^A-Za-z]*"
    r"(?P<state>needs a reviewer|not applicable|could not run|pass|fail)\b(?P<evidence>.*)$",
    re.I,
)


@dataclass(frozen=True)
class Result:
    id: str  # `SoT:K6.2`, `CACHES:B2`, or `F1`
    level: str
    state: str
    evidence: str
    line: str

    @property
    def bare(self) -> str:
        return self.id.split(":", 1)[-1]


def parse_results(report: str) -> list[Result]:
    """Every line that starts with a requirement id and gives its level and one of the five results."""
    found: list[Result] = []
    for line in report.splitlines():
        candidates = [one for one in (_PREFIXED.search(line), _OWN.search(line)) if one is not None]
        if not candidates:
            continue
        match = min(candidates, key=lambda one: one.start())
        if match.re is _PREFIXED:
            ident = f"{match.group('prefix')}:{match.group('id').rstrip('.')}"
        else:
            ident = match.group("id")
        if not _DECORATION.match(line[: match.start()]):
            continue
        tail = _RESULT.match(line[match.end():])
        if tail is None:
            continue
        level = (tail.group("l1") or tail.group("l2") or "").strip()
        found.append(Result(ident, level, tail.group("state").lower(), tail.group("evidence"), line))
    return found


def by_id(results: list[Result]) -> dict[str, list[Result]]:
    table: dict[str, list[Result]] = {}
    for one in results:
        table.setdefault(one.id, []).append(one)
    return table


def location_lines(report: str, name: str) -> list[str]:
    """Lines that name a location and are not a requirement's result line (those say "8 present, 1 absent" in bulk)."""
    return [
        line
        for line in report.splitlines()
        if name in line
        and not parse_results(line)
        and not _PREFIXED.search(line)
        and not re.search(r"\d+\s+absent", line)
    ]


def mentions(text: str, bare_id: str) -> bool:
    """Whether the id stands in the text as a whole token (K6.1 is not K6.1a)."""
    return re.search(r"(?<![A-Za-z0-9.])" + re.escape(bare_id) + r"(?![A-Za-z0-9])", text) is not None


# --- the guidelines the tool is checked against (its own copy, C1) ---------------------------------------------


def read_sot_records(yaml_path: Path) -> dict[str, dict[str, object]]:
    """id -> {level, checks} for each record of SOURCE_OF_TRUTH_REQUIREMENTS.yaml (a line scan; no yaml module)."""
    records: dict[str, dict[str, object]] = {}
    current: str | None = None
    for line in yaml_path.read_text(encoding="utf-8").splitlines():
        start = re.match(r"\s*- id: (\S+)\s*$", line)
        if start:
            current = start.group(1)
            records[current] = {}
            continue
        if current is None:
            continue
        level = re.match(r"\s+level: (\S+)\s*$", line)
        if level:
            records[current]["level"] = level.group(1)
        check = re.match(r"\s+check: (.*)$", line)
        if check:
            records[current]["checks"] = [part.strip() for part in check.group(1).split(";") if part.strip()]
    return {key: value for key, value in records.items() if "level" in value}


def read_caches_ids(caches_md: Path) -> list[str]:
    """The ids of CACHES.md's Core requirements: the bold headings between `## Core requirements` and the next `## `."""
    ids: list[str] = []
    inside = False
    for line in caches_md.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            inside = line.strip() == "## Core requirements"
            continue
        if inside:
            heading = re.match(r"\*\*((?:B|K|Rd)\d+) — ", line)
            if heading:
                ids.append(heading.group(1))
    return ids


# --- snapshots --------------------------------------------------------------------------------------------------


def snapshot(*roots: Path) -> dict[str, tuple]:
    """Every file, folder and link under the roots, hidden and ignored ones included, with a hash of its bytes."""
    table: dict[str, tuple] = {}
    for root in roots:
        for folder, folders, files in os.walk(root, followlinks=False):
            for name in folders + files:
                full = Path(folder) / name
                key = f"{root.name}/{full.relative_to(root).as_posix()}"
                if full.is_symlink():
                    table[key] = ("link", os.readlink(full))
                elif full.is_dir():
                    table[key] = ("dir",)
                else:
                    table[key] = ("file", hashlib.sha256(full.read_bytes()).hexdigest())
    return table


def diff_snapshots(before: dict[str, tuple], after: dict[str, tuple]) -> list[str]:
    changes = [f"created {key}" for key in sorted(after.keys() - before.keys())]
    changes += [f"deleted {key}" for key in sorted(before.keys() - after.keys())]
    changes += [f"changed {key}" for key in sorted(before.keys() & after.keys()) if before[key] != after[key]]
    return changes


# --- running the tool -------------------------------------------------------------------------------------------


@dataclass
class Proc:
    returncode: int | None
    stdout: str
    stderr: str
    hung: bool = False


class Lab:
    def __init__(self, base: Path, cli: Path, guidelines: Path, index_tool: Path, bun: str):
        self.base = base
        self.cli = cli
        self.guidelines = guidelines
        self.index_tool = index_tool
        self.bun = bun
        self.home = base / "home"
        self.home.mkdir()
        self.elsewhere = base / "elsewhere"
        self.elsewhere.mkdir()
        self.out = base / "out"
        self.out.mkdir()
        self._count = 0

    # -- environment

    def env(self, home: Path | None = None) -> dict[str, str]:
        env = {key: os.environ[key] for key in ("PATH", "LANG", "LC_ALL") if key in os.environ}
        env.update(
            HOME=str(home or self.home),
            GIT_CONFIG_GLOBAL="/dev/null",
            GIT_CONFIG_NOSYSTEM="1",
            GIT_AUTHOR_NAME="Probe Author",
            GIT_AUTHOR_EMAIL="author@example.invalid",
            GIT_COMMITTER_NAME="Probe Committer",
            GIT_COMMITTER_EMAIL="committer@example.invalid",
            GIT_TERMINAL_PROMPT="0",
            GIT_CEILING_DIRECTORIES=str(self.base),
        )
        return env

    def git(self, repo: Path, *args: str) -> str:
        done = subprocess.run(
            ["git", *args], cwd=repo, env=self.env(), capture_output=True, text=True, stdin=subprocess.DEVNULL
        )
        assert done.returncode == 0, f"fixture git {' '.join(args)} failed: {done.stderr}"
        return done.stdout.strip()

    # -- fixture projects

    def project(
        self,
        files: dict[str, str] | None = None,
        *,
        ignore: list[str] | None = None,
        commit: bool = True,
        name: str | None = None,
    ) -> Path:
        self._count += 1
        root = self.base / (name or f"proj{self._count}")
        root.mkdir()
        self.git(root, "init", "-q")
        self.git(root, "checkout", "-q", "-b", "main")
        all_files = dict(files or {})
        if ignore:
            all_files[".gitignore"] = "\n".join(ignore) + "\n"
        for rel, text in all_files.items():
            target = root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        self.git(root, "add", "-A")
        if commit:
            self.git(root, "commit", "-q", "-m", "fixture")
        return root

    def commit_all(self, root: Path, message: str) -> str:
        self.git(root, "add", "-A")
        self.git(root, "commit", "-q", "--allow-empty", "-m", message)
        return self.git(root, "rev-parse", "HEAD")

    # -- running

    def run(
        self,
        args: list[str],
        *,
        cwd: Path | None = None,
        home: Path | None = None,
        timeout: int = 90,
    ) -> Proc:
        process = subprocess.Popen(
            [self.bun, str(self.cli), *args],
            cwd=str(cwd or self.elsewhere),
            env=self.env(home),
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            start_new_session=True,
        )
        try:
            stdout, stderr = process.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            stdout, stderr = process.communicate()
            return Proc(None, stdout or "", stderr or "", hung=True)
        return Proc(process.returncode, stdout, stderr)

    def report(
        self, project: Path, *extra: str, home: Path | None = None, since: str | None = None
    ) -> tuple[Proc, str]:
        """Run the full report with `--out`; return the process and the report text ('' when none was written)."""
        self._count += 1
        out_file = self.out / f"report{self._count}.md"
        args = ["--project", str(project), "--home", str(home or self.home), "--out", str(out_file), *extra]
        if since is not None:
            args += ["--since", since]
        proc = self.run(args, home=home)
        assert not proc.hung, "the tool did not finish (it blocked, probably opening a file it must not open)"
        text = out_file.read_text(encoding="utf-8") if out_file.is_file() else ""
        return proc, text

    def warn(self, project: Path, *, home: Path | None = None) -> Proc:
        return self.run(["--project", str(project), "--home", str(home or self.home), "--warn"], home=home)

    # -- the guidelines the tool is checked against

    def sot(self) -> dict[str, dict[str, object]]:
        return read_sot_records(self.guidelines / "SOURCE_OF_TRUTH_REQUIREMENTS.yaml")

    def caches(self) -> list[str]:
        return read_caches_ids(self.guidelines / "CACHES.md")

    def all_ids(self) -> list[str]:
        return [f"SoT:{one}" for one in self.sot()] + [f"CACHES:{one}" for one in self.caches()]

    # -- reading

    def results(self, report: str) -> list[Result]:
        return parse_results(report)

    def failing_musts(self, report: str) -> set[str]:
        return {
            one.id
            for one in parse_results(report)
            if one.level.upper() == "MUST" and one.state in ("fail", "could not run")
        }


def _find_index_tool(product: Path) -> Path | None:
    for start in (product.resolve(), Path(__file__).resolve()):
        for parent in start.parents:
            candidate = parent / "tools" / "memory_index.py"
            if candidate.is_file():
                return candidate
    return None


