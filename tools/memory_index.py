#!/usr/bin/env python3
"""memory_index.py — build `project-memory/INDEX.md` from the entry files in `project-memory/entries/`.

Run:  python3 tools/memory_index.py                  # write mode: rebuild the working tree's INDEX.md
      python3 tools/memory_index.py --check          # check mode: rebuild from the staging area and compare
      python3 tools/memory_index.py --check <rev>    # check mode: the same, from a commit

One file per memory, one generated index over them. The index is never hand-edited: the same entries always give
the same bytes (file names in code-point order, no date, no host, no locale), so "run the script and compare" is an
exact check — the way Kubernetes and Cog keep generated files honest. Write mode reads the working tree; check mode
reads git objects only and writes nothing, which is what makes the pre-commit hook safe to run on every commit.

Do not edit `project-memory/INDEX.md` by hand — regenerate it here. When it conflicts in a merge, resolve the entry
files, re-run this script and stage the result (G3.2). A test (tests/test_memory_index.py) runs `--check HEAD` on the
repository, so drift is caught, not hand-synced.
"""
from __future__ import annotations

import argparse
import difflib
import os
import re
import subprocess
import sys
import tempfile
import urllib.parse
from dataclasses import dataclass, field
from pathlib import Path

# Rd3.1: INDEX.md must fit the strictest start-file limit of the agents that read it. These two numbers are the
# design's example, not a measurement: the agy row of the start-load limits table in docs/memory-system/CACHES.md
# gives "24,000 bytes per rule file" (and 12,000 characters in other reports, a conflict W-4 records). They stay
# examples until the readers' load paths are measured (B4.1). Nothing is ever cut to fit — over the limit, write
# mode still writes the whole file and check mode fails (B4.3).
MAX_LINES = 200
MAX_BYTES = 24_000

MEMORY_DIR = "project-memory"
ENTRIES_DIR = "project-memory/entries"
INDEX_PATH = "project-memory/INDEX.md"

# The five kinds of W1.1. Runbooks (R-) were dropped by EJ on 2026-10-13; an R- file is not an entry (B1.1).
ENTRY_NAME = re.compile(r"[DFLOH]-[^/]+\.md")
PREFIX_KIND = {
    "D": "decision",
    "F": "fact",
    "L": "lesson",
    "O": "observation",
    "H": "hypothesis",
}
KINDS = tuple(PREFIX_KIND.values())
STATUSES = ("active", "superseded", "retired")
WHY = "**Why:**"

# W1.1's id form (B2.3, G4.2): `DD-MM-xxxxxx-YYYY`, ASCII classes on purpose — `\d` and str.isdigit() also match
# non-ASCII digits. The form only: no calendar check, so `31-02-a1b2c3-2026` is a valid id.
ID_FORM = re.compile(r"[0-9]{2}-[0-9]{2}-[0-9a-z]{6}-[0-9]{4}")
# The two git conflict markers SoT K6.3 names, each at the start of a line (B2.7). `=======` is left out: it is
# also a Markdown heading underline.
CONFLICT_MARKERS = ("<<<<<<<", ">>>>>>>")

TITLE = "# Project memory index"
GENERATED_NOTE = (
    "<!-- Generated by tools/memory_index.py from project-memory/entries/. "
    "Do not edit by hand. Rebuild: python3 tools/memory_index.py -->"
)
HEADER_TEXT = f"{TITLE}\n\n{GENERATED_NOTE}\n\n"
NO_ENTRIES_LINE = "(no active entries)\n"
HOW_TO_FIX = "stage the entries, run `python3 tools/memory_index.py`, then `git add project-memory/INDEX.md`"


class GitError(Exception):
    """A git command failed. The message is the one the user gets."""


def report(text: str) -> None:
    """Print a problem to stderr. stdout is flushed first, so a piped run (a hook, CI) reads in order."""
    sys.stdout.flush()
    print(text, file=sys.stderr)


# --- one entry --------------------------------------------------------------------------------------------------


@dataclass
class Entry:
    """One entry file, parsed and checked. `errors` stops the build; `warnings` do not."""

    name: str
    entry_id: str = ""
    kind: str = ""
    status: str = ""
    claim: str = ""
    has_why: bool = False
    tracked: bool = True
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def is_active(self) -> bool:
        return self.status == "active"


def parse_header(lines: list[str]) -> tuple[dict[str, str], int | None, str | None]:
    """Read the top-level `id:`, `kind:` and `status:` from the header block.

    Line 1 must be `---` and the header ends at the next line that is exactly `---`. Indented lines are nested
    fields, not top-level ones. Returns the fields, the index of the closing line, and the first problem.
    """
    if not lines or lines[0] != "---":
        return {}, None, "no header"
    try:
        end = lines.index("---", 1)
    except ValueError:
        return {}, None, "header is not closed"
    fields: dict[str, str] = {}
    for line in lines[1:end]:
        if not line or line[0].isspace():
            continue
        key, separator, value = line.partition(":")
        name = key.strip()
        if separator and name in ("id", "kind", "status"):
            fields[name] = unquote(value)
    return fields, end, None


def unquote(value: str) -> str:
    """Strip whitespace and one pair of surrounding quotes from a header value."""
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def read_claim(body: list[str]) -> tuple[str, bool]:
    """Return the claim (the body up to `**Why:**`, blank lines dropped, whitespace runs collapsed) and whether
    a `**Why:**` line was found."""
    parts: list[str] = []
    has_why = False
    for line in body:
        if line.startswith(WHY):
            has_why = True
            break
        parts.append(" ".join(line.split()))
    return " ".join(part for part in parts if part), has_why


def check_content(entry: Entry) -> None:
    """Every entry needs an id and a known status; an active entry needs a kind, a matching file prefix, a
    `**Why:**` line and a claim. The same content problems are only warnings in an inactive entry, which gets
    no line anyway (B2.5).

    An entry git does not know about is an error in every status (B1.2): until it is staged it is not part of
    the memory, so it can neither be checked nor indexed — naming it is what tells the writer to `git add` it.
    """
    if not entry.tracked:
        entry.errors.append("not known to git, git add it first")
    problems: list[str] = []
    if entry.kind not in KINDS:
        problems.append(f"kind {entry.kind!r} is not one of {' / '.join(KINDS)}")
    elif PREFIX_KIND.get(entry.name[:1]) != entry.kind:
        problems.append(f"kind {entry.kind!r} does not match the {entry.name[:1]}- file prefix")
    if not entry.has_why:
        problems.append(f"no {WHY} line")
    if not entry.claim:
        problems.append("empty claim")
    if entry.is_active:
        entry.errors.extend(problems)
    else:
        entry.warnings.extend(problems)


def flag_conflict_markers(entry: Entry, lines: list[str]) -> None:
    """A line that starts with `<<<<<<<` or `>>>>>>>` is a merge that was never resolved: an error in every
    status, because a marker in the body would otherwise be indexed as a claim (B2.7)."""
    for number, line in enumerate(lines, start=1):
        if line.startswith(CONFLICT_MARKERS):
            entry.errors.append(f"unresolved conflict marker on line {number}: {line.strip()!r}")


def parse_entry(name: str, text: str, *, tracked: bool = True) -> Entry:
    """Parse one entry's text. CRLF becomes LF; never raises."""
    entry = Entry(name=name, tracked=tracked)
    lines = text.replace("\r\n", "\n").split("\n")
    flag_conflict_markers(entry, lines)
    fields, end, header_problem = parse_header(lines)
    if header_problem:
        entry.errors.append(header_problem)
        return entry
    entry.entry_id = fields.get("id", "")
    entry.kind = fields.get("kind", "")
    entry.status = fields.get("status", "")
    entry.claim, entry.has_why = read_claim(lines[end + 1:])
    if not entry.entry_id:
        entry.errors.append("empty id")
    elif not ID_FORM.fullmatch(entry.entry_id):
        entry.errors.append(f"id {entry.entry_id!r} is not in the form DD-MM-xxxxxx-YYYY (x: a lowercase letter or digit)")
    if entry.status not in STATUSES:
        entry.errors.append(f"status {entry.status!r} is not one of {' / '.join(STATUSES)}")
    if not is_utf8(entry.name):
        entry.errors.append("file name is not valid UTF-8")
    check_content(entry)
    return entry


def is_utf8(text: str) -> bool:
    """A name that came back from git with undecodable bytes cannot be written into the index."""
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        return False
    return True


def entry_from_bytes(name: str, raw: bytes, *, tracked: bool = True) -> Entry:
    """Parse an entry from its bytes; undecodable bytes are a problem, not a crash (B2.6)."""
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        entry = Entry(name=name, tracked=tracked)
        entry.errors.append("not valid UTF-8")
        return entry
    return parse_entry(name, text, tracked=tracked)


def flag_duplicate_ids(entries: list[Entry]) -> None:
    """No two entries share an id, in any status (B2.3, G4.2)."""
    seen: set[str] = set()
    for entry in entries:
        if not entry.entry_id:
            continue
        if entry.entry_id in seen:
            entry.errors.append(f"duplicate id {entry.entry_id}")
        seen.add(entry.entry_id)


# --- the index ---------------------------------------------------------------------------------------------------


def index_link(name: str) -> str:
    """The relative link to an entry file, percent-encoded so spaces, `#` and non-ASCII names resolve (B3.1)."""
    return f"entries/{urllib.parse.quote(name)}"


def render_entry(entry: Entry) -> str:
    return f"- [{entry.entry_id}]({index_link(entry.name)}) {entry.kind}: {entry.claim}\n"


def active_entries(entries: list[Entry]) -> list[Entry]:
    """Only an active entry gets a line. A superseded or retired entry is not even in the index (B3.1)."""
    return [entry for entry in entries if entry.is_active]


def render_index(entries: list[Entry]) -> bytes:
    """The exact bytes of INDEX.md: a fixed head, then one line per active entry in file-name order."""
    lines = "".join(render_entry(entry) for entry in entries) if entries else NO_ENTRIES_LINE
    return (HEADER_TEXT + lines).encode("utf-8")


def measure(rendered: bytes) -> tuple[int, int]:
    return rendered.count(b"\n"), len(rendered)


def size_report(rendered: bytes) -> str:
    lines, byte_count = measure(rendered)
    return f"INDEX.md: {lines}/{MAX_LINES} lines, {byte_count}/{MAX_BYTES} bytes"


def over_limit(rendered: bytes) -> bool:
    lines, byte_count = measure(rendered)
    return lines > MAX_LINES or byte_count > MAX_BYTES


def print_diff(current: bytes, built: bytes) -> None:
    """A unified diff of the index in the snapshot against the index the entries produce."""
    before = current.decode("utf-8", "replace").splitlines()
    after = built.decode("utf-8", "replace").splitlines()
    for line in difflib.unified_diff(before, after, f"a/{INDEX_PATH}", f"b/{INDEX_PATH}", lineterm=""):
        report(line)


# --- git ---------------------------------------------------------------------------------------------------------


def git(args: list[str], *, cwd: Path | None = None, stdin: bytes | None = None) -> bytes:
    """Run a git command and return its raw bytes. Read-only: `GIT_OPTIONAL_LOCKS=0` keeps git from touching the
    index file, which check mode must not change (C1.4)."""
    env = dict(os.environ, GIT_OPTIONAL_LOCKS="0")
    result = subprocess.run(["git", *args], cwd=cwd, env=env, input=stdin, capture_output=True)
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", "replace").strip() or f"exit {result.returncode}"
        raise GitError(f"git {' '.join(args)} failed: {detail}")
    return result.stdout


def split_nul(raw: bytes) -> list[str]:
    """Split NUL-separated git output into text, decoding paths as UTF-8 whatever the locale says."""
    return [part.decode("utf-8", "surrogateescape") for part in raw.split(b"\0") if part]


def entry_name(path: str) -> str:
    r"""The file name of an entry: a `^[DFLOH]-[^/]+\.md$` name directly in `project-memory/entries/`."""
    return path[len(ENTRIES_DIR) + 1:]


def is_entry_path(path: str) -> bool:
    """B1.1: only files directly in the entries folder, with a matching name. No subfolders, no dotfiles, no
    INDEX.md, no other prefix."""
    prefix = f"{ENTRIES_DIR}/"
    if not path.startswith(prefix):
        return False
    name = path[len(prefix):]
    return "/" not in name and ENTRY_NAME.fullmatch(name) is not None


def repo_root() -> Path:
    """The repository of the current working directory — the script works on wherever it is run from."""
    return Path(os.fsdecode(git(["rev-parse", "--show-toplevel"]).strip()))


def working_tree_paths(repo: Path) -> tuple[list[str], list[str]]:
    """The entry paths git knows about in the working tree, and the matching ones it does not know yet (B1.2)."""
    tracked = set(split_nul(git(["ls-files", "-z", "--cached", "--", ENTRIES_DIR], cwd=repo)))
    others = set(
        split_nul(git(["ls-files", "-z", "--others", "--exclude-standard", "--", ENTRIES_DIR], cwd=repo))
    )
    return sorted(p for p in tracked if is_entry_path(p)), sorted(p for p in others - tracked if is_entry_path(p))


def snapshot_paths(repo: Path, rev: str | None) -> dict[str, str]:
    """Every path under `project-memory/` in the snapshot with its blob id — the staging area by default, or a
    commit. NUL-separated, so names with spaces and non-ASCII characters survive (B1.3)."""
    blobs: dict[str, str] = {}
    if rev:
        for meta, path in records(git(["ls-tree", "-r", "-z", rev, "--", MEMORY_DIR], cwd=repo)):
            fields = meta.split()  # <mode> <type> <sha>
            if len(fields) == 3 and is_object_id(fields[2]):
                blobs[path] = fields[2]
    else:
        for meta, path in records(git(["ls-files", "-s", "-z", "--", MEMORY_DIR], cwd=repo)):
            fields = meta.split()  # <mode> <sha> <stage>
            # Stage 0 is what a commit would take, and the only stage a tree without conflicts has.
            if len(fields) == 3 and fields[2] == "0" and is_object_id(fields[1]):
                blobs[path] = fields[1]
    return blobs


def records(raw: bytes) -> list[tuple[str, str]]:
    """Split `<meta>\\t<path>\\0` listing output into its meta part and its path."""
    return [record.partition("\t")[::2] for record in split_nul(raw)]


def is_object_id(value: str) -> bool:
    return len(value) == 40 and all(character in "0123456789abcdef" for character in value)


def cat_file_batch(repo: Path, shas: list[str]) -> dict[str, bytes]:
    """Read every blob with one `git cat-file --batch` call. One call per file is about 20 times slower."""
    if not shas:
        return {}
    raw = git(["cat-file", "--batch"], cwd=repo, stdin=("\n".join(shas) + "\n").encode("ascii"))
    blobs: dict[str, bytes] = {}
    position = 0
    while position < len(raw):
        newline = raw.index(b"\n", position)
        header = raw[position:newline].split()
        position = newline + 1
        if len(header) < 3:  # "<sha> missing" — the blob is gone
            continue
        size = int(header[2])
        blobs[header[0].decode("ascii")] = raw[position:position + size]
        position += size + 1
    return blobs


# --- the two modes -----------------------------------------------------------------------------------------------


def gather(entries: list[Entry]) -> None:
    """Sort by file name (code points, never locale collation), find duplicate ids and report every problem."""
    entries.sort(key=lambda entry: entry.name)
    flag_duplicate_ids(entries)
    for entry in entries:
        for problem in entry.errors:
            report(f"{entry.name}: {problem}")
        for problem in entry.warnings:
            report(f"{entry.name}: {problem} (warning)")


def working_tree_entries(repo: Path) -> list[Entry]:
    """Read every entry file in the working tree: the ones git knows about, and the ones it does not yet.

    Write mode reads the working tree, not the index: a tracked or newly staged entry always gets its current
    content. A file git does not know yet is parsed like any other and is an error whatever its status (B1.2) —
    it is named, with the `git add` that fixes it, and nothing is written.
    """
    tracked, untracked = working_tree_paths(repo)
    entries: list[Entry] = []
    for path in sorted(tracked):
        name = entry_name(path)
        try:
            raw = (repo / path).read_bytes()
        except OSError as error:
            entry = Entry(name=name)
            # Unreadable, or deleted without `git rm`: its status cannot be known, and an active entry must never
            # be skipped (DESIGN, Must not 4), so this is an error like an unreadable untracked file.
            entry.errors.append(f"cannot be read in the working tree: {error.strerror} (deleted? git rm it)")
            entries.append(entry)
            continue
        entries.append(entry_from_bytes(name, raw))
    for path in untracked:
        try:
            raw = (repo / path).read_bytes()
        except OSError as error:
            entry = Entry(name=entry_name(path), tracked=False)
            entry.errors.append(f"cannot be read: {error.strerror}")
            entries.append(entry)
            continue
        entries.append(entry_from_bytes(entry_name(path), raw, tracked=False))
    return entries


def snapshot_memory(repo: Path, rev: str | None) -> tuple[list[Entry], bytes | None] | None:
    """The entries and the index of the snapshot, or None when the snapshot has no `project-memory/` at all
    (C1.3). Every blob comes out of a single `git cat-file --batch` call."""
    paths = snapshot_paths(repo, rev)
    if not paths:
        return None
    wanted = [path for path in sorted(paths) if is_entry_path(path)]
    shas = {paths[path] for path in wanted}
    if INDEX_PATH in paths:
        shas.add(paths[INDEX_PATH])
    blobs = cat_file_batch(repo, sorted(shas))
    entries = []
    for path in wanted:
        name = entry_name(path)
        if paths[path] not in blobs:
            entry = Entry(name=name)
            entry.errors.append("blob is missing from the snapshot")
        else:
            entry = entry_from_bytes(name, blobs[paths[path]])
        entries.append(entry)
    current = blobs.get(paths[INDEX_PATH]) if INDEX_PATH in paths else None
    return entries, current


def write_index(repo: Path) -> int:
    if not (repo / ENTRIES_DIR).is_dir():
        print(f"nothing to index: no {ENTRIES_DIR}/")
        return 0
    entries = working_tree_entries(repo)
    gather(entries)
    if any(entry.errors for entry in entries):
        return 1
    rendered = render_index(active_entries(entries))
    print(size_report(rendered))
    index = repo / INDEX_PATH
    if index.exists() and index.read_bytes() == rendered:
        print(f"{INDEX_PATH} is up to date")
    else:
        write_atomically(index, rendered)
        print(f"wrote {INDEX_PATH}")
    if over_limit(rendered):
        print_over_limit()
    return 0


def write_atomically(path: Path, rendered: bytes) -> None:
    """Write a temporary file in the same folder and rename it over the target, so a reader never sees half a
    file. Nothing is ever truncated to fit (B4.3): the whole file is written."""
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=".INDEX.md.", suffix=".tmp")
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(rendered)
        os.replace(temporary, path)
    except BaseException:
        os.unlink(temporary)
        raise


def check_index(repo: Path, rev: str | None) -> int:
    where = rev or "the staging area"
    if head_is_unborn(repo):
        print(f"nothing to check: HEAD names no commit yet, so {where} holds no snapshot")
        return 0
    if rev and not rev_is_commit(repo, rev):
        report(f"{rev}: names no commit in this repository, so {INDEX_PATH} cannot be checked against it")
        return 1
    snapshot = snapshot_memory(repo, rev)
    if snapshot is None:
        print(f"nothing to check: no {MEMORY_DIR}/ in {where}")
        return 0
    entries, current = snapshot
    gather(entries)
    if any(entry.errors for entry in entries):
        return 1
    rendered = render_index(active_entries(entries))
    print(size_report(rendered))
    if current != rendered:
        report(f"{INDEX_PATH} in {where} does not match what these entries build. To fix it: {HOW_TO_FIX}")
        print_diff(current or b"", rendered)
        return 1
    if over_limit(rendered):
        report(f"{INDEX_PATH} in {where} is over the limit. Nothing is cut to fit: retire or merge entries "
               f"until it fits ({HOW_TO_FIX})")
        return 1
    print(f"{INDEX_PATH} in {where} is up to date")
    return 0


def git_succeeds(repo: Path, args: list[str]) -> bool:
    """Whether a read-only git command succeeds. The two calls below are how HEAD and a rev are told apart."""
    try:
        git(args, cwd=repo)
    except GitError:
        return False
    return True


def head_is_unborn(repo: Path) -> bool:
    """A repository with no commits yet: `HEAD` names no commit but still points at a branch (C1.3). It is not
    a bad revision — there is simply nothing committed to check, so it passes."""
    return (git_succeeds(repo, ["symbolic-ref", "--quiet", "HEAD"])
            and not git_succeeds(repo, ["rev-parse", "--verify", "--quiet", "HEAD^{commit}"]))


def rev_is_commit(repo: Path, rev: str) -> bool:
    """Whether the revision names a commit at all. One that does not is a failure, not an empty snapshot (C1.2):
    a check that silently passed would report every drifting index as correct."""
    return git_succeeds(repo, ["rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}"])


def print_over_limit() -> None:
    print("warning: INDEX.md is over the limit. Nothing is cut to fit (B4.3): retire or merge entries instead.")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build or check project-memory/INDEX.md from the entry files.",
    )
    parser.add_argument("--check", action="store_true",
                        help="check the snapshot (the staging area, or <rev>) instead of writing")
    parser.add_argument("rev", nargs="?", help="the commit to check; only with --check")
    args = parser.parse_args()
    if args.rev and not args.check:
        parser.error("a revision only applies to --check")
    for stream in (sys.stdout, sys.stderr):  # never let a non-ASCII file name fail to print under LC_ALL=C
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    try:
        repo = repo_root()
        return check_index(repo, args.rev) if args.check else write_index(repo)
    except GitError as error:
        report(f"memory_index.py: {error}")
        return 1
    except OSError as error:  # e.g. INDEX.md is a folder, or project-memory/ is read-only: a problem, not a crash
        report(f"{error.filename or 'memory_index.py'}: {error.strerror or error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())