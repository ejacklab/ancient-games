@pytest.mark.parametrize("mode", ["staged", "commit"])
def test_snapshot_reads_use_nul_paths_and_one_batch(tmp_path, mode):
    """B1.3 — paths with spaces and non-ASCII characters require NUL listing and one blob batch."""
    repo = make_repo(tmp_path)
    write_entry(repo, "D-a b.md", id="space", claim="Space.")
    write_entry(repo, "F-é.md", id="accent", kind="fact", claim="Accent.")
    expected = HEADER + (
        b"- [space](entries/D-a%20b.md) decision: Space.\n"
        b"- [accent](entries/F-%C3%A9.md) fact: Accent.\n"
    )
    (repo / INDEX).write_bytes(expected)
    args = snapshot_args(repo, mode)
    shim_dir = tmp_path / "git-shim"
    shim_dir.mkdir()
    trace = tmp_path / "git-calls.jsonl"
    real_git = shutil.which("git")
    shim = shim_dir / "git"
    shim.write_text(
        f"#!{sys.executable}\nimport json, os, sys\n"
        "with open(os.environ['MEMORY_GIT_TRACE'], 'a') as stream:\n"
        "    stream.write(json.dumps(sys.argv[1:]) + '\\n')\n"
        "os.execv(os.environ['MEMORY_REAL_GIT'], ['git', *sys.argv[1:]])\n",
        encoding="utf-8",
    )
    shim.chmod(0o755)
    result = run_index(repo, *args, env_extra={
        "PATH": str(shim_dir) + os.pathsep + os.environ["PATH"],
        "MEMORY_REAL_GIT": real_git, "MEMORY_GIT_TRACE": str(trace),
    })
    assert result.returncode == 0, output(result)
    calls = [json.loads(line) for line in trace.read_text().splitlines()]
    listings = [call for call in calls if ("ls-files" if mode == "staged" else "ls-tree") in call]
    assert listings and all(
        any(arg.startswith("-") and not arg.startswith("--") and "z" in arg for arg in call)
        for call in listings
    ), calls
    batches = [call for call in calls if "cat-file" in call]
    assert len(batches) == 1 and "--batch" in batches[0], calls


