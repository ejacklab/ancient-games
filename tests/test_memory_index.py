def isolated_env(env_extra=None):
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env.update(
        GIT_CONFIG_GLOBAL="/dev/null",
        GIT_CONFIG_NOSYSTEM="1",
        GIT_AUTHOR_NAME="Memory index tests",
        GIT_AUTHOR_EMAIL="memory-tests@example.invalid",
        GIT_COMMITTER_NAME="Memory index tests",
        GIT_COMMITTER_EMAIL="memory-tests@example.invalid",
        PYTHONDONTWRITEBYTECODE="1",
    )
    if env_extra:
        env.update(env_extra)
    return env


def git(repo, *args, check=True, env_extra=None):
    result = subprocess.run(
        ["git", *args], cwd=repo, env=isolated_env(env_extra),
        capture_output=True, text=True, encoding="utf-8",
    )
    if check:
        assert result.returncode == 0, result.stdout + result.stderr
    return result


def make_repo(tmp_path, *, copy_tool=True):
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-b", "main")
    attribute_paths = [REPO / ".gitattributes"]
    if (REPO / "project-memory").is_dir():
        attribute_paths.extend((REPO / "project-memory").rglob(".gitattributes"))
    for source in attribute_paths:
        if source.is_file():
            destination = repo / source.relative_to(REPO)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    if copy_tool:
        assert (REPO / "tools/memory_index.py").is_file(), "tools/memory_index.py is not built yet"
        (repo / "tools").mkdir()
        shutil.copy2(REPO / "tools/memory_index.py", repo / "tools/memory_index.py")
        shutil.copytree(REPO / ".githooks", repo / ".githooks")
    git(repo, "add", "-A")
    git(repo, "commit", "--allow-empty", "-m", "Initial test snapshot")
    (repo / ENTRIES).mkdir(parents=True)
    return repo


def write_entry(repo, name="D-one.md", *, id="14-10-a1b2c3-2026", kind="decision",
                status="active", claim="Use code-point order for the index.", raw=None):
    path = repo / ENTRIES / name
    path.parent.mkdir(parents=True, exist_ok=True)
    if raw is None:
        raw = (
            f"---\nid: {id}\nkind: {kind}\nstatus: {status}\n---\n{claim}\n\n"
            "**Why:** locale order made collaborators rewrite the file.\n\n"
            "**How to apply:** sort with Python's default str order.\n"
        )
    path.write_bytes(raw if isinstance(raw, bytes) else raw.encode("utf-8"))
    return path


def run_index(repo, *args, env_extra=None):
    return subprocess.run(
        [sys.executable, "tools/memory_index.py", *args], cwd=repo,
        env=isolated_env(env_extra), capture_output=True, text=True, encoding="utf-8",
    )


def output(result):
    return result.stdout + result.stderr


def stage_single_entry(repo):
    write_entry(repo)
    (repo / INDEX).write_bytes(SINGLE_INDEX)
    git(repo, "add", "-A")


def snapshot_args(repo, mode):
    if mode == "write":
        return ()
    git(repo, "add", "-A")
    if mode == "commit":
        git(repo, "commit", "-m", "Memory snapshot")
        return ("--check", "HEAD")
    return ("--check",)


def size_numbers(result, expected):
    matches = SIZE_LINE.findall(output(result))
    assert len(matches) == 1, output(result)
    lines, max_lines, byte_count, max_bytes = map(int, matches[0])
    assert lines == len(expected.splitlines())
    assert byte_count == len(expected)
    assert max_lines > 0 and max_bytes > 0
    return max_lines, max_bytes


