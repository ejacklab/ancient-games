"""Acceptance tests for the second review's accepted Python findings (runs/20261018-finish-everything, step
reproduce), one per finding, each built from the finding's own input. They drive `tools/memory_index.py` as a
subprocess over temporary repositories, the way tests/test_memory_index.py does. Written by the reproduce step
(Claude), which wrote none of tools/memory_index.py.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
INDEX = Path("project-memory/INDEX.md")
ENTRIES = Path("project-memory/entries")
# Transcribed from DESIGN step 6, never obtained from the generator (as in tests/test_memory_index.py).
HEADER = (
    b"# Project memory index\n\n"
    b"<!-- Generated by tools/memory_index.py from project-memory/entries/. Do not edit by hand. "
    b"Rebuild: python3 tools/memory_index.py -->\n\n"
)
EMPTY_INDEX = HEADER + b"(no active entries)\n"


def isolated_env():
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env.update(
        GIT_CONFIG_GLOBAL="/dev/null",
        GIT_CONFIG_NOSYSTEM="1",
        GIT_AUTHOR_NAME="Memory index tests",
        GIT_AUTHOR_EMAIL="memory-tests@example.invalid",
        GIT_COMMITTER_NAME="Memory index tests",
        GIT_COMMITTER_EMAIL="memory-tests@example.invalid",
        PYTHONDONTWRITEBYTECODE="1",
    )
    return env


def git(repo, *args):
    result = subprocess.run(["git", *args], cwd=repo, env=isolated_env(), capture_output=True, text=True,
                            encoding="utf-8")
    assert result.returncode == 0, result.stdout + result.stderr
    return result


def new_repo(tmp_path, *init_args):
    """A repository with the tool copied in and nothing committed (make_repo of test_memory_index.py, without its
    initial commit, so a test can choose an unborn HEAD or an object format)."""
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-b", "main", *init_args)
    (repo / "tools").mkdir()
    shutil.copy2(REPO / "tools/memory_index.py", repo / "tools/memory_index.py")
    (repo / ENTRIES).mkdir(parents=True)
    return repo


def write_entry(repo, name="D-17-10-abc123-2026-a.md", *, id="17-10-abc123-2026", kind="decision",
                status="active", claim="Use code-point order for the index."):
    path = repo / ENTRIES / name
    path.write_bytes((
        f"---\nid: {id}\nkind: {kind}\nstatus: {status}\n---\n{claim}\n\n"
        "**Why:** locale order made collaborators rewrite the file.\n\n"
        "**How to apply:** sort with Python's default str order.\n"
    ).encode("utf-8"))
    return path


def run_index(repo, *args):
    return subprocess.run([sys.executable, "tools/memory_index.py", *args], cwd=repo, env=isolated_env(),
                          capture_output=True, text=True, encoding="utf-8")


def output(result):
    return result.stdout + result.stderr


def test_C7_A1_unborn_head_still_checks_the_staging_area(tmp_path):
    """C7+A1 — before the first commit `git ls-files -s` works, so a staged entry with status: invalid must fail."""
    repo = new_repo(tmp_path)
    write_entry(repo, status="invalid")
    (repo / INDEX).write_bytes(EMPTY_INDEX)
    git(repo, "add", "-A")
    unborn = subprocess.run(["git", "rev-parse", "--verify", "-q", "HEAD"], cwd=repo, env=isolated_env(),
                            capture_output=True)
    assert unborn.returncode != 0  # HEAD names no commit yet
    assert "D-17-10-abc123-2026-a.md" in git(repo, "ls-files", "-s").stdout
    result = run_index(repo, "--check")
    message = output(result)
    assert "nothing to check" not in message, message
    assert "status 'invalid'" in message, message
    assert result.returncode == 1, message


def test_C8_sha256_repository_staged_memory_is_checked(tmp_path):
    """C8 — in a SHA-256 repository a committed INDEX.md that says 'wrong' must fail, not look absent."""
    repo = new_repo(tmp_path, "--object-format=sha256")
    write_entry(repo)
    (repo / INDEX).write_bytes(b"wrong\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-m", "Memory with a wrong index")
    assert len(git(repo, "rev-parse", "HEAD").stdout.strip()) == 64
    result = run_index(repo, "--check")
    message = output(result)
    assert "nothing to check" not in message, message
    assert "does not match" in message, message
    assert result.returncode == 1, message


def test_A2_stale_index_over_the_limit_reports_both(tmp_path):
    """A2 — an over-limit rendered index with a stale staged INDEX.md must get the over-limit failure too."""
    repo = new_repo(tmp_path)
    git(repo, "commit", "--allow-empty", "-m", "Initial test snapshot")
    write_entry(repo, claim="x" * 25_000)  # one line well over 24,000 bytes
    (repo / INDEX).write_bytes(EMPTY_INDEX)  # stale: the entry is active and has no line
    git(repo, "add", "-A")
    result = run_index(repo, "--check")
    message = output(result)
    assert "does not match" in message, message.splitlines()[:2]  # the mismatch is still reported
    assert "over the limit" in message, message.splitlines()[:2]
    assert result.returncode == 1, message
